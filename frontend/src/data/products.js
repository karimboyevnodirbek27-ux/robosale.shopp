// Rasm URL ni olish.
// Backend lokal rejimda /uploads/... qaytaradi - unga server manzilini qo'shamiz.
// Cloudinary yoki tashqi URL bo'lsa, o'zgartirmasdan qaytaramiz.
export const getImageUrl = (imagePath) => {
  if (!imagePath) return '/placeholder.svg';
  if (/^https?:\/\//i.test(imagePath) || imagePath.startsWith('data:')) {
    return imagePath;
  }
  if (imagePath.startsWith('/uploads/')) {
    return `${SERVER_URL}${imagePath}`;
  }
  return imagePath;
};
